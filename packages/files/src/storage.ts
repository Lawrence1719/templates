import "server-only"

import { mkdir, readFile, rm, writeFile } from "node:fs/promises"
import path from "node:path"

import { AwsClient } from "aws4fetch"
import { z } from "zod"

/** File contents (backed by a plain ArrayBuffer, which fetch/Response accept). */
export type Bytes = Uint8Array<ArrayBuffer>

/** Where file bytes live. Implement this to use another backend. */
export interface Storage {
  put(key: string, bytes: Bytes, contentType: string): Promise<void>
  get(key: string): Promise<Bytes | null>
  delete(key: string): Promise<void>
}

// Keys are always "<org uuid>/<file uuid>", generated by us. Anything else is refused,
// so a bad key can never escape the storage root.
const KEY = /^[0-9a-f-]{36}\/[0-9a-f-]{36}$/
function assertKey(key: string) {
  if (!KEY.test(key)) throw new Error("Invalid storage key")
}

/** Local disk, for development and tests. */
export class LocalStorage implements Storage {
  constructor(private root: string) {}
  private file(key: string) {
    assertKey(key)
    return path.join(this.root, key)
  }
  async put(key: string, bytes: Bytes) {
    const f = this.file(key)
    await mkdir(path.dirname(f), { recursive: true })
    await writeFile(f, bytes)
  }
  async get(key: string) {
    try {
      return new Uint8Array(await readFile(this.file(key)))
    } catch (e) {
      if ((e as NodeJS.ErrnoException).code === "ENOENT") return null
      throw e
    }
  }
  async delete(key: string) {
    await rm(this.file(key), { force: true })
  }
}

/** Any S3-compatible service: AWS S3, Cloudflare R2, Supabase Storage, MinIO. */
export class S3Storage implements Storage {
  private client: AwsClient
  constructor(
    private cfg: {
      endpoint: string
      bucket: string
      accessKeyId: string
      secretAccessKey: string
      region: string
    },
  ) {
    this.client = new AwsClient({
      accessKeyId: cfg.accessKeyId,
      secretAccessKey: cfg.secretAccessKey,
      region: cfg.region,
      service: "s3",
    })
  }
  private url(key: string) {
    assertKey(key)
    return `${this.cfg.endpoint.replace(/\/$/, "")}/${this.cfg.bucket}/${key}`
  }
  async put(key: string, bytes: Bytes, contentType: string) {
    const res = await this.client.fetch(this.url(key), {
      method: "PUT",
      body: bytes,
      headers: { "Content-Type": contentType },
    })
    if (!res.ok) throw new Error(`Storage PUT failed: ${res.status}`)
  }
  async get(key: string) {
    const res = await this.client.fetch(this.url(key))
    if (res.status === 404) return null
    if (!res.ok) throw new Error(`Storage GET failed: ${res.status}`)
    return new Uint8Array(await res.arrayBuffer())
  }
  async delete(key: string) {
    const res = await this.client.fetch(this.url(key), { method: "DELETE" })
    if (!res.ok && res.status !== 404) throw new Error(`Storage DELETE failed: ${res.status}`)
  }
}

let storage: Storage | undefined

/** S3 when S3_BUCKET is configured, otherwise local disk at FILES_DIR (default ./.storage). */
export function getStorage(): Storage {
  if (storage) return storage
  const env = z
    .object({
      S3_ENDPOINT: z.url().optional(),
      S3_BUCKET: z.string().min(1).optional(),
      S3_ACCESS_KEY_ID: z.string().optional(),
      S3_SECRET_ACCESS_KEY: z.string().optional(),
      S3_REGION: z.string().default("auto"),
      FILES_DIR: z.string().default(".storage"),
    })
    .parse(process.env)
  if (env.S3_BUCKET) {
    if (!env.S3_ENDPOINT || !env.S3_ACCESS_KEY_ID || !env.S3_SECRET_ACCESS_KEY)
      throw new Error(
        "S3_BUCKET is set but S3_ENDPOINT / S3_ACCESS_KEY_ID / S3_SECRET_ACCESS_KEY are missing",
      )
    storage = new S3Storage({
      endpoint: env.S3_ENDPOINT,
      bucket: env.S3_BUCKET,
      accessKeyId: env.S3_ACCESS_KEY_ID,
      secretAccessKey: env.S3_SECRET_ACCESS_KEY,
      region: env.S3_REGION,
    })
  } else {
    storage = new LocalStorage(path.resolve(env.FILES_DIR))
  }
  return storage
}

/** For tests: use a specific backend. */
export function setStorage(s: Storage) {
  storage = s
}
